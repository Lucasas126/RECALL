from __future__ import annotations

import json
import re
import secrets
from datetime import datetime, timedelta
from pathlib import Path
from typing import Collection, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from src.config.levels import LevelField
from src.config.model_refs import CLAUDE_SUBSCRIPTION, prefix_of, provider_of
from src.config.models import ReasoningEffort
from src.core.sources.base import Source
from src.utils.files import atomic_write_text
from src.utils.i18n import InputError, UserMessageError

_CHAT_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_TITLE_CHARS = 60
DEFAULT_DISPOSABLE_RETENTION_DAYS = 30
_DISPOSABLE_SUFFIX = ".disposable.json"
_ORIGIN_SUFFIX = ".origin.json"
_TASK_SUFFIX = ".task.json"
_UNREAD_SUFFIX = ".unread.json"
DEFAULT_ORIGIN = "web"  # chats without an origin marker predate it and count as web chats
_ORIGIN_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")


class ChatModel(BaseModel):
    """A persistent chat-specific model reference; `provider` records who served it when it was chosen.

    A bare id belongs to the user's main provider at the time it is used, so `provider` is informational
    for bare ids; a `<provider>:` reference must name the same provider.
    """

    model_config = ConfigDict(extra="forbid")

    provider: Literal["openrouter", "ollama", "claude_subscription"] = "openrouter"
    id: str = Field(strict=True, min_length=1, max_length=256)
    zdr: bool | None = Field(default=None, strict=True)  # None follows the user's require_zdr

    @model_validator(mode="after")
    def _provider_matches_id(self) -> "ChatModel":
        named = prefix_of(self.id)
        if (named is not None and self.provider != named) or (named is None and self.provider == CLAUDE_SUBSCRIPTION):
            raise ValueError("the chat model's provider does not match its model reference")
        if self.provider == CLAUDE_SUBSCRIPTION and self.zdr:
            raise ValueError("Claude subscription models cannot be used with zero data retention")
        return self


class ChatReasoningEffort(BaseModel):
    """A chat-owned reasoning effort that replaces the agent default for that chat."""

    model_config = ConfigDict(extra="forbid")

    effort: ReasoningEffort


def _normalize_title(text: str) -> str:
    """Collapse whitespace, drop wrapping quotes and cap the length for display."""
    title = " ".join(text.split()).strip(" \"'`*")
    if len(title) > _TITLE_CHARS:
        title = title[: _TITLE_CHARS - 1] + "…"
    return title


class ChatTitle(BaseModel):
    """A chat title, generated by the small naming model or chosen by the user."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=1, max_length=_TITLE_CHARS)
    generated: bool = False  # written by the naming model (dropped when its source message is rewound)


class ChatDisposable(BaseModel):
    """Marks a disposable chat: not learned from, removed after a period of inactivity."""

    model_config = ConfigDict(extra="forbid")

    created_at: str


class ChatOrigin(BaseModel):
    """Where a chat was created / belongs to (`web`, `telegram`, ...); stored in `<chat_id>.origin.json`."""

    model_config = ConfigDict(extra="forbid")

    origin: str


class ChatTask(BaseModel):
    """Marks the hidden chat of a subagent task (`<chat_id>.task.json`): its parentage, grant and worker prompt.

    A task chat is also disposable (not learned from) and is left out of chat lists, the latest chat and pruning.
    The agent reads its restrictions from this stored mark, so they survive a rebuild and the model cannot drop them.
    """

    model_config = ConfigDict(extra="forbid")

    task_id: str
    parent_agent_id: str
    parent_chat_id: str
    depth: int = 1
    groups: list[str] = Field(default_factory=list)  # the tool groups the worker was granted
    instructions: str = ""  # the worker's system prompt, written by the parent
    backends: list[str] = Field(default_factory=list)  # terminal backends granted (always manual); "terminal" is then in groups
    inherit: bool = False  # ephemeral worker started with `inherit`: the parent's approval mode on its backends (never `off`)
    title: str = ""  # the task's title, for attributing its approvals in the parent chat
    unattended: bool = False  # nobody watches: manual and dangerous actions are denied (phase 7 launches these)
    automation: bool = False  # started by an automation: it may also message its owner (`notify`, `files_send`)
    kind: str = Field(default="ephemeral", pattern=r"^(ephemeral|agent)$")  # `agent`: an existing agent of the user runs it, with its own SOUL
    remember: bool = False  # agent kind only: an ordinary hidden chat (reviewable) whose agent may write its own memory
    # the level cap of the worker: the lower of the launching agent's level and the target's own; None = its own level
    level: Optional[LevelField] = None
    created_at: str = ""


class ChatMetadataError(UserMessageError, RuntimeError):
    """Chat model metadata could not be read or saved."""


class ConversationsSource(Source):
    """Chats with the user: one JSONL file per chat (one turn per line), named `<chat_id>.jsonl`."""

    def __init__(self, root: Path):
        # not writable to the agent's tools; chats are managed via the methods below
        super().__init__("conversations", root, readable=True, writable=False, indexed=True)
        self.reviewable_only = False  # a dream's tools: disposable and task chats are neither listed, searched nor read

    def _private_names(self) -> set[str]:
        return self.disposable_chats() | self.task_chats() if self.reviewable_only else set()

    def _is_private_file(self, rel_path: str, private: set[str]) -> bool:
        return bool(private) and rel_path.split("/")[-1].split(".")[0] in private

    def walk(self, exts: set[str] | None = None) -> list[str]:
        private = self._private_names()
        return [rel for rel in super().walk(exts) if not self._is_private_file(rel, private)]

    def list(self, subpath: str = "") -> list[str]:
        private = self._private_names()
        return [rel for rel in super().list(subpath) if not self._is_private_file(rel.rstrip("/"), private)]

    def read(self, rel_path: str) -> str:
        if self._is_private_file(rel_path, self._private_names()):
            raise PermissionError(f"{rel_path} belongs to a disposable or task chat, which a dream never reads")
        return super().read(rel_path)

    def _path(self, chat_id: str) -> Path:
        if not _CHAT_ID_RE.match(chat_id):
            raise InputError("invalid {kind} id: {value!r}", kind="chat", value=chat_id)
        return self.resolve(f"{chat_id}.jsonl")

    def exists_chat(self, chat_id: str) -> bool:
        return self._path(chat_id).is_file()

    def _model_path(self, chat_id: str) -> Path:
        if not self.exists_chat(chat_id):
            raise FileNotFoundError(f"chat not found: {chat_id}")
        return self.resolve(f"{chat_id}.model.json")

    def model_selection(self, chat_id: str) -> ChatModel | None:
        """Read a chat's model override; older chats have no override."""
        path = self._model_path(chat_id)
        try:
            return ChatModel.model_validate_json(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None
        except (OSError, UnicodeError, ValidationError) as exc:
            raise ChatMetadataError("Could not read model selection for chat {chat_id}.", chat_id=chat_id) from exc

    def set_model(self, chat_id: str, model_id: str, *, zdr: bool | None = None, main: str = "openrouter") -> ChatModel:
        """Persist an override after the caller validates model availability; bare ids belong to `main`.

        `zdr` is the chat's own flag; None stores none, so the chat follows the user's setting.
        """
        path = self._model_path(chat_id)
        selection = ChatModel(provider=provider_of(model_id, main), id=model_id, zdr=zdr)
        try:
            atomic_write_text(path, selection.model_dump_json(exclude_none=True) + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save model selection for chat {chat_id}.", chat_id=chat_id) from exc
        return selection

    def clear_model(self, chat_id: str) -> None:
        """Remove the LLM override so the chat inherits the current user default."""
        try:
            self._model_path(chat_id).unlink(missing_ok=True)
        except OSError as exc:
            raise ChatMetadataError("Could not save model selection for chat {chat_id}.", chat_id=chat_id) from exc

    def reasoning_effort_selection(self, chat_id: str) -> ChatReasoningEffort | None:
        """Read a chat's reasoning effort override; None means the agent default applies."""
        self._model_path(chat_id)
        path = self.resolve(f"{chat_id}.effort.json")
        try:
            return ChatReasoningEffort.model_validate_json(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None
        except (OSError, UnicodeError, ValidationError) as exc:
            raise ChatMetadataError("Could not read reasoning effort for chat {chat_id}.", chat_id=chat_id) from exc

    def set_reasoning_effort(self, chat_id: str, effort: ReasoningEffort | None) -> None:
        """Persist or clear a chat's reasoning effort after the caller validates the model supports it."""
        self._model_path(chat_id)
        path = self.resolve(f"{chat_id}.effort.json")
        try:
            if effort is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write_text(path, ChatReasoningEffort(effort=effort).model_dump_json() + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save reasoning effort for chat {chat_id}.", chat_id=chat_id) from exc

    def generated_title(self, chat_id: str) -> str | None:
        """Read a chat's stored title; None means the first user message is used."""
        self._model_path(chat_id)
        path = self.resolve(f"{chat_id}.title.json")
        try:
            return ChatTitle.model_validate_json(path.read_text(encoding="utf-8")).title
        except FileNotFoundError:
            return None
        except (OSError, UnicodeError, ValidationError) as exc:
            raise ChatMetadataError("Could not read title for chat {chat_id}.", chat_id=chat_id) from exc

    def set_generated_title(self, chat_id: str, title: str) -> str:
        """Persist a generated title unless the chat already has one; returns the stored title."""
        existing = self.generated_title(chat_id)
        if existing is not None:
            return existing
        stored = _normalize_title(title)
        if not stored:
            raise ValueError("chat title is empty")
        return self._write_title(chat_id, stored, generated=True)

    def rename(self, chat_id: str, title: str) -> str:
        """Persist a user-chosen title, replacing any generated one; returns the stored title."""
        self._model_path(chat_id)
        stored = " ".join(title.split())
        if not stored:
            raise InputError("chat title cannot be empty")
        if len(stored) > _TITLE_CHARS:
            raise InputError("chat title cannot exceed {limit} characters", limit=_TITLE_CHARS)
        return self._write_title(chat_id, stored)

    def _write_title(self, chat_id: str, title: str, *, generated: bool = False) -> str:
        path = self.resolve(f"{chat_id}.title.json")
        try:
            atomic_write_text(path, ChatTitle(title=title, generated=generated).model_dump_json() + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save title for chat {chat_id}.", chat_id=chat_id) from exc
        return title

    def _disposable_path(self, chat_id: str) -> Path:
        return self.resolve(f"{chat_id}{_DISPOSABLE_SUFFIX}")

    def is_disposable(self, chat_id: str) -> bool:
        """Whether the chat is disposable (excluded from Dream and the index, removed after inactivity)."""
        self._path(chat_id)  # validates the id
        return self._disposable_path(chat_id).is_file()

    def disposable_chats(self) -> set[str]:
        """The ids of every disposable chat that still has its transcript."""
        marked = {p.name[: -len(_DISPOSABLE_SUFFIX)] for p in self.root.iterdir() if p.name.endswith(_DISPOSABLE_SUFFIX)}
        return {chat_id for chat_id in marked if _CHAT_ID_RE.match(chat_id) and self.resolve(f"{chat_id}.jsonl").is_file()}

    def set_disposable(self, chat_id: str, disposable: bool) -> None:
        """Mark or unmark a chat as disposable; marking an already disposable chat keeps its original stamp."""
        if not self.exists_chat(chat_id):
            raise FileNotFoundError(f"chat not found: {chat_id}")
        path = self._disposable_path(chat_id)
        try:
            if not disposable:
                path.unlink(missing_ok=True)
            elif not path.is_file():
                stamp = datetime.now().astimezone().isoformat(timespec="seconds")
                atomic_write_text(path, ChatDisposable(created_at=stamp).model_dump_json() + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save the disposable flag for chat {chat_id}.", chat_id=chat_id) from exc

    def _unread_path(self, chat_id: str) -> Path:
        return self.resolve(f"{chat_id}{_UNREAD_SUFFIX}")

    def has_unread(self, chat_id: str) -> bool:
        """Whether a reply finished in this chat that nobody has opened yet (state kept on the server)."""
        self._path(chat_id)  # validates the id
        return self._unread_path(chat_id).is_file()

    def set_unread(self, chat_id: str, unread: bool) -> None:
        """Mark or clear the chat's unread reply; a vanished chat is ignored (it was deleted meanwhile)."""
        if not self.exists_chat(chat_id):
            return
        path = self._unread_path(chat_id)
        try:
            if not unread:
                path.unlink(missing_ok=True)
            else:
                atomic_write_text(path, json.dumps({"since": datetime.now().astimezone().isoformat(timespec="seconds")}) + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save the unread mark of chat {chat_id}.", chat_id=chat_id) from exc

    def _origin_path(self, chat_id: str) -> Path:
        return self.resolve(f"{chat_id}{_ORIGIN_SUFFIX}")

    def origin(self, chat_id: str) -> str:
        """The chat's origin (`web`, `telegram`, ...); `web` when it has no (readable) marker."""
        self._path(chat_id)  # validates the id
        try:
            return ChatOrigin.model_validate_json(self._origin_path(chat_id).read_text(encoding="utf-8")).origin
        except (OSError, UnicodeError, ValidationError):
            return DEFAULT_ORIGIN

    def set_origin(self, chat_id: str, origin: str) -> None:
        """Record the chat's origin (e.g. a future hand-over from web to Telegram just sets `telegram`)."""
        if not isinstance(origin, str) or not _ORIGIN_RE.match(origin):
            raise InputError("Invalid chat origin: {origin}.", origin=str(origin))
        if not self.exists_chat(chat_id):
            raise FileNotFoundError(f"chat not found: {chat_id}")
        try:
            atomic_write_text(self._origin_path(chat_id), ChatOrigin(origin=origin).model_dump_json() + "\n")
        except OSError as exc:
            raise ChatMetadataError("Could not save the origin of chat {chat_id}.", chat_id=chat_id) from exc

    def _task_path(self, chat_id: str) -> Path:
        return self.resolve(f"{chat_id}{_TASK_SUFFIX}")

    def is_task_chat(self, chat_id: str) -> bool:
        """Whether the chat is the hidden chat of a subagent task."""
        self._path(chat_id)  # validates the id
        return self._task_path(chat_id).is_file()

    def task_chats(self) -> set[str]:
        """The ids of every task chat that still has its transcript."""
        marked = {p.name[: -len(_TASK_SUFFIX)] for p in self.root.iterdir() if p.name.endswith(_TASK_SUFFIX)}
        return {chat_id for chat_id in marked if _CHAT_ID_RE.match(chat_id) and self.resolve(f"{chat_id}.jsonl").is_file()}

    def task_mark(self, chat_id: str) -> ChatTask | None:
        """The task mark of a chat, None for an ordinary one. An unreadable mark raises: it never reads as ordinary."""
        self._path(chat_id)  # validates the id
        try:
            return ChatTask.model_validate_json(self._task_path(chat_id).read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None
        except (OSError, UnicodeError, ValidationError) as exc:
            raise ChatMetadataError("Could not read the task mark of chat {chat_id}.", chat_id=chat_id) from exc

    def last_activity(self, chat_id: str) -> datetime:
        """When the chat last changed: the modification time of its transcript."""
        return datetime.fromtimestamp(self._path(chat_id).stat().st_mtime).astimezone()

    def expires_at(self, chat_id: str, retention_days: int = DEFAULT_DISPOSABLE_RETENTION_DAYS) -> datetime:
        """When a disposable chat is removed: its last activity plus the retention period."""
        return self.last_activity(chat_id) + timedelta(days=retention_days)

    def expired_disposable(
        self, retention_days: int = DEFAULT_DISPOSABLE_RETENTION_DAYS, now: datetime | None = None,
    ) -> list[str]:
        """Disposable chats whose last activity is older than the retention period; normal chats never qualify."""
        moment = (now or datetime.now()).astimezone()
        expired = []
        for chat_id in sorted(self.disposable_chats()):
            try:
                if self.expires_at(chat_id, retention_days) <= moment:
                    expired.append(chat_id)
            except FileNotFoundError:
                continue
        return expired

    def create(self, *, disposable: bool = False, origin: str = DEFAULT_ORIGIN, task: ChatTask | None = None) -> str:
        """Create an empty chat and return its id; a `task` makes it the hidden, disposable chat of that task."""
        chat_id = f"{datetime.now():%Y%m%d-%H%M%S}-{secrets.token_hex(3)}"
        path = self._path(chat_id)
        if task is not None:
            disposable = not task.remember  # a `remember` task chat is hidden but ordinary: Dream and the index may use it
            try:  # the mark goes first, so an empty-chat prune can never see the chat unmarked
                atomic_write_text(self._task_path(chat_id), task.model_dump_json() + "\n")
            except OSError as exc:
                raise ChatMetadataError("Could not save the task mark of chat {chat_id}.", chat_id=chat_id) from exc
        path.touch(exist_ok=False)
        if disposable:
            self.set_disposable(chat_id, True)
        self.set_origin(chat_id, origin)
        return chat_id

    def delete_chat(self, chat_id: str) -> None:
        path = self._path(chat_id)
        if not path.is_file():
            raise FileNotFoundError(f"chat not found: {chat_id}")
        metadata = self._model_path(chat_id)
        effort = self.resolve(f"{chat_id}.effort.json")
        title = self.resolve(f"{chat_id}.title.json")
        disposable = self._disposable_path(chat_id)
        origin = self._origin_path(chat_id)
        task = self._task_path(chat_id)
        unread = self._unread_path(chat_id)
        legacy_transcription = self.resolve(f"{chat_id}.stt.json")  # per-chat STT overrides are no longer read
        removed = self._removed_path(chat_id)
        path.unlink()
        removed.unlink(missing_ok=True)
        metadata.unlink(missing_ok=True)
        effort.unlink(missing_ok=True)
        title.unlink(missing_ok=True)
        disposable.unlink(missing_ok=True)
        origin.unlink(missing_ok=True)
        task.unlink(missing_ok=True)
        unread.unlink(missing_ok=True)
        legacy_transcription.unlink(missing_ok=True)

    def _removed_path(self, chat_id: str) -> Path:
        return self.resolve(f"{chat_id}.removed.json")

    def truncate_from(self, chat_id: str, index: int) -> list[dict]:
        """Rewind a chat: keep the turns before `index` and drop that user turn and everything after it.

        `index` is the position of the turn in the stored file, counting every stored turn (tool turns
        included). Only a user turn can be the target. The dropped turns are appended to the
        `<chat_id>.removed.json` sidecar so nothing is irrecoverably lost; a generated title is dropped
        when the first message goes. Returns the dropped turns. The caller must ensure no reply is running.
        """
        turns = self.load(chat_id)
        if isinstance(index, bool) or not isinstance(index, int) or not 0 <= index < len(turns):
            raise InputError("that message does not exist in this chat", code="invalid_edit_target")
        if turns[index].get("role") != "user":
            raise InputError("only your own messages can be edited", code="invalid_edit_target")
        dropped = turns[index:]
        sidecar = self._removed_path(chat_id)
        try:
            try:
                history = json.loads(sidecar.read_text(encoding="utf-8"))
                if not isinstance(history, list):
                    history = []
            except (FileNotFoundError, ValueError):
                history = []
            history.append({"removed_at": datetime.now().astimezone().isoformat(timespec="seconds"), "turns": dropped})
            atomic_write_text(sidecar, json.dumps(history, ensure_ascii=False) + "\n")
            atomic_write_text(
                self._path(chat_id), "".join(json.dumps(t, ensure_ascii=False) + "\n" for t in turns[:index]),
            )
            if index == 0:
                title = self.resolve(f"{chat_id}.title.json")
                try:
                    if ChatTitle.model_validate_json(title.read_text(encoding="utf-8")).generated:
                        title.unlink(missing_ok=True)
                except (OSError, UnicodeError, ValidationError):
                    pass
        except OSError as exc:
            raise ChatMetadataError("Could not rewind chat {chat_id}.", chat_id=chat_id) from exc
        return dropped

    def append(self, chat_id: str, role: str, content: str, *, drop_checkpoint: bool = False, **extra) -> dict:
        """Append a turn to an existing chat as one JSONL line.

        `drop_checkpoint` first removes the chat's last line when it is a checkpoint (see `checkpoint`): the final
        turn replaces the partial one written while the reply was still running.
        """
        path = self._path(chat_id)
        if not path.is_file():
            raise FileNotFoundError(f"chat not found: {chat_id}")
        if drop_checkpoint:
            self._drop_checkpoint(path)
        turn = {
            "role": role,
            "content": content,
            "ts": datetime.now().astimezone().isoformat(timespec="seconds"),
            **extra,
        }
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(turn, ensure_ascii=False) + "\n")
        return turn

    def checkpoint(self, chat_id: str, content: str, *, replace: bool, **extra) -> dict:
        """Save the assistant turn still being written, so a restart in the middle does not lose what was done.

        The turn is stored as `interrupted` with `checkpoint: true`. With `replace`, the previous checkpoint of the
        same reply (the chat's last line) is overwritten instead of adding another turn.
        """
        return self.append(
            chat_id, "assistant", content, drop_checkpoint=replace, **extra, interrupted=True, checkpoint=True,
        )

    @staticmethod
    def _drop_checkpoint(path: Path) -> None:
        """Remove the file's last line when it is a checkpoint turn; any other last line stays."""
        with open(path, "rb+") as fh:
            data = fh.read().rstrip(b"\n")
            start = data.rfind(b"\n") + 1
            try:
                last = json.loads(data[start:])
            except ValueError:
                return
            if isinstance(last, dict) and last.get("checkpoint") is True:
                fh.truncate(start)

    def load(self, chat_id: str) -> list[dict]:
        """Read all turns of a chat."""
        path = self._path(chat_id)
        if not path.is_file():
            raise FileNotFoundError(f"chat not found: {chat_id}")
        turns = []
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line:
                turns.append(json.loads(line))
        return turns

    def chats(self, *, include_internal: bool = False) -> list[str]:
        """List chat ids, oldest first; subagent task chats are internal and only listed with `include_internal`."""
        hidden = set() if include_internal else self.task_chats()
        return sorted(p.stem for p in self.root.iterdir() if p.suffix == ".jsonl" and p.stem not in hidden)

    def prune_empty(self, keep: str | Collection[str] | None = None) -> list[str]:
        """Delete unused chats except the given chat id(s) and task chats (which start empty); return the removed ids."""
        removed = []
        kept = {keep} if isinstance(keep, str) else set(keep or ())
        for path in self.root.iterdir():
            if path.suffix != ".jsonl" or path.stem in kept or self._task_path(path.stem).is_file():
                continue
            if not path.read_text(encoding="utf-8").strip():
                self.delete_chat(path.stem)
                removed.append(path.stem)
        return removed

    def latest(self) -> str | None:
        """The id of the most recently modified chat, if any (task chats are not candidates)."""
        hidden = self.task_chats()
        files = [p for p in self.root.iterdir() if p.suffix == ".jsonl" and p.stem not in hidden]
        return max(files, key=lambda p: p.stat().st_mtime).stem if files else None

    def summary(self, chat_id: str, retention_days: int = DEFAULT_DISPOSABLE_RETENTION_DAYS) -> dict:
        """Chat metadata: title (user-chosen or generated, else first user message), turn count, last activity
        its `origin` (`web` when unmarked) and, for a disposable chat, `disposable` and the ISO time it will be removed (`expires_at`)."""
        turns = self.load(chat_id)
        title = self.generated_title(chat_id)
        if title is None:
            first_user = next((t["content"] for t in turns if t.get("role") == "user"), "")
            if isinstance(first_user, list):
                first_user = next(
                    (part.get("text", "") for part in first_user if part.get("type") == "text"),
                    "[attachment]",
                )
            title = _normalize_title(first_user)
        updated = turns[-1].get("ts") if turns else None
        if not updated:
            mtime = self._path(chat_id).stat().st_mtime
            updated = datetime.fromtimestamp(mtime).astimezone().isoformat(timespec="seconds")
        disposable = self.is_disposable(chat_id)
        expires = self.expires_at(chat_id, retention_days).isoformat(timespec="seconds") if disposable else None
        return {
            "id": chat_id, "title": title, "turns": len(turns), "updated": updated,
            "disposable": disposable, "expires_at": expires, "origin": self.origin(chat_id),
        }
